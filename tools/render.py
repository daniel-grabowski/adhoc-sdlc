#!/usr/bin/env python3
"""Render adhoc-sdlc prompt variants from neutral templates + per-runtime tool maps.

Source of truth: templates/ (prose with {{PLACEHOLDER}} tokens) + runtimes/<rt>.json
(per-runtime tool bindings). For each active runtime this substitutes its placeholders
and writes the explicit, tool-named files into the runtime's output tree, so the shipped
prompt names a concrete tool (e.g. `AskUserQuestion` on Claude Code) instead of a soft
description. Build-time tool: run it before committing a template or mapping change,
the same way tools/sync-helper.sh mirrors the .py helper.

Usage:
  python3 tools/render.py                # render every active runtime
  python3 tools/render.py --runtime codex   # render one runtime (ignores its active flag)
  python3 tools/render.py --check        # verify on-disk files match; non-zero on drift
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
import re

REPO_ROOT = Path(__file__).resolve().parent.parent
TEMPLATES_DIR = REPO_ROOT / "templates"
RUNTIMES_DIR = REPO_ROOT / "runtimes"
PLACEHOLDER_RE = re.compile(r"\{\{([A-Z_]+)\}\}")
GENERATED_NOTE = (
    "GENERATED by tools/render.py from templates/{template} + runtimes/{runtime}.json. "
    "DO NOT EDIT here; edit the template and re-run tools/render.py."
)


def _header(template_rel: str, runtime: str) -> str:
    note = GENERATED_NOTE.format(template=template_rel, runtime=runtime)
    return "<!-- " + note + " -->\n"


def _insert_header(content: str, header: str) -> str:
    # Put the marker AFTER a leading YAML frontmatter block (--- ... ---) so the
    # frontmatter still parses; otherwise put it at the very top.
    if content.startswith("---\n"):
        end = content.find("\n---\n", 4)
        if end != -1:
            cut = end + len("\n---\n")
            return content[:cut] + header + content[cut:]
    return header + content


def render_one(template_rel: str, placeholders: dict, runtime: str) -> str:
    tpath = TEMPLATES_DIR / template_rel
    if not tpath.is_file():
        raise SystemExit(f"ERROR: template not found: templates/{template_rel}")
    text = tpath.read_text(encoding="utf-8")
    tokens = sorted(set(PLACEHOLDER_RE.findall(text)))
    missing = [t for t in tokens if t not in placeholders]
    if missing:
        raise SystemExit(
            f"ERROR: unmapped placeholders {missing} in templates/{template_rel} "
            f"for runtime '{runtime}' (add them to runtimes/{runtime}.json)"
        )
    rendered = PLACEHOLDER_RE.sub(lambda m: placeholders[m.group(1)], text)
    rendered = _insert_header(rendered, _header(template_rel, runtime))
    leftover = sorted(set(PLACEHOLDER_RE.findall(rendered)))
    if leftover:
        raise SystemExit(
            f"ERROR: leftover placeholders {leftover} after rendering templates/{template_rel}"
        )
    return rendered


def load_specs() -> list[dict]:
    if not RUNTIMES_DIR.is_dir():
        raise SystemExit(f"ERROR: runtimes dir not found: {RUNTIMES_DIR}")
    specs = []
    for jf in sorted(RUNTIMES_DIR.glob("*.json")):
        specs.append(json.loads(jf.read_text(encoding="utf-8")))
    return specs


def select(specs: list[dict], only: str | None):
    for spec in specs:
        rt = spec.get("runtime")
        if only is not None:
            if rt == only:
                yield spec
        elif spec.get("active", False):
            yield spec


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description="Render adhoc-sdlc variants from templates + runtime tool maps.")
    ap.add_argument("--runtime", help="render only this runtime (overrides its active flag)")
    ap.add_argument("--check", action="store_true", help="verify on-disk files match the render; write nothing, non-zero exit on drift")
    args = ap.parse_args(argv)

    specs = load_specs()
    selected = list(select(specs, args.runtime))
    if args.runtime and not selected:
        raise SystemExit(f"ERROR: runtime '{args.runtime}' not found in runtimes/")

    drift: list[str] = []
    written = 0
    done_runtimes: list[str] = []
    for spec in selected:
        rt = spec["runtime"]
        placeholders = spec.get("placeholders", {})
        files = spec.get("files", [])
        if not files:
            continue
        done_runtimes.append(rt)
        for template_rel, output_rel in files:
            rendered = render_one(template_rel, placeholders, rt)
            opath = REPO_ROOT / output_rel
            if args.check:
                current = opath.read_text(encoding="utf-8") if opath.is_file() else None
                if current != rendered:
                    drift.append(output_rel)
            else:
                opath.parent.mkdir(parents=True, exist_ok=True)
                opath.write_text(rendered, encoding="utf-8")
                written += 1

    label = ", ".join(done_runtimes) if done_runtimes else "(no runtimes with files)"
    if args.check:
        if drift:
            print("DRIFT: these outputs differ from templates + mapping (run tools/render.py to regenerate):")
            for d in drift:
                print(f"  {d}")
            return 1
        print(f"check OK: {label} up to date")
        return 0
    print(f"rendered {written} files for: {label}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
